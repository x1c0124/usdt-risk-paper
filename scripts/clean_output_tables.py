"""
Clean up output/tables/ to the minimal set the paper needs.

What this script does:
  - Keeps only files in KEEP_SPEC in output/tables/
  - Moves redundant / superseded output files into output/tables/_archive/
    (does NOT delete — you can recover if you change your mind)
  - Writes output/tables/_archive/README.md explaining why each archived
    file is there, so reviewers reading the repo understand the choice
  - Skips hidden files (e.g. .gitkeep)

Run from project root:
  python scripts/clean_output_tables.py

Safe to re-run: idempotent. Run after every run_analysis.py to keep tables clean.
"""
from pathlib import Path
import shutil
from datetime import datetime

ROOT = Path(__file__).resolve().parent.parent
TABLES = ROOT / "output" / "tables"
ARCHIVE = TABLES / "_archive"

# Files the paper actually uses, organized by section.
# (filename, paper_section, description)
KEEP_SPEC = [
    # Chapter 5.1 — Extreme events + descriptive
    ("extreme_events.csv", "5.1", "Top-N extreme peg deviations (bilateral)"),
    ("event_study_table.csv", "5.1 / App A", "Six-episode event study window statistics"),
    ("yearly_summary_bilateral.csv", "App B", "Year-by-year dev_up/down, ES_up/down, depeg freq"),

    # Chapter 5.2–5.3 — Regime classification + conditional risk
    ("regime_contingency.csv", "5.2", "2x2 table: CryptoStress × MacroStress (core finding)"),
    ("regime_risk_summary.csv", "5.3", "4-state regime risk metrics (mean by regime)"),
    ("stress_vs_normal_summary.csv", "5.3", "2-state comparison: sigma / ES / depeg_freq"),

    # Chapter 5.4 — Main dual-regime regressions (bilateral)
    ("regression_dual_regime_ES_down.txt", "5.4", "Main: ES_down ~ CryptoStress + MacroStress + SOFR"),
    ("regression_dual_regime_ES_up.txt", "5.4", "Main: ES_up ~ CryptoStress + MacroStress + SOFR"),

    # Chapter 5.5 — Extended robustness
    ("regression_extended.txt", "5.5", "Extended: + DXY + EM_FX + CREDIT_SPREAD (BAA10Y)"),
    ("regression_extended_ES_up.txt", "5.5", "Extended ES_up with same RHS"),
    ("regression_extended_standardized.txt", "5.5", "Standardized continuous regressors (Cond.No. robustness)"),
    ("regression_extended_params.csv", "5.5", "Params table for main extended regression"),

    # Appendix — robustness
    ("regression_extended_TED_subsample.txt", "App C", "TED window sub-sample (2018-2022)"),
    ("em_episode_descriptives.csv", "App D", "Turkey/Argentina/Russia EM windows, USDT response"),
    ("regression_summary_vol.txt", "App E", "Robustness: Stress = BTC vol > 95th pct"),

    # Derived — master tables built by build_thesis_tables.py
    ("master_regression_table.csv", "Derived", "All regression coefs in one CSV (build_thesis_tables.py)"),
]

KEEP_NAMES = {name for name, _, _ in KEEP_SPEC}

# Files explicitly known to be regenerated by run_analysis.py but superseded.
EXPLICIT_ARCHIVE = {
    "regression_dual_regime_ES.txt": (
        "Superseded: identical to regression_dual_regime_ES_down.txt "
        "(ES == ES_down by construction)"
    ),
    "regression_summary.txt": (
        "Superseded: old single-stress spec (ES ~ Stress + VIX + SOFR); "
        "dual-regime version is canonical"
    ),
    "regression_bilateral_ES_down.txt": (
        "Superseded: identical to regression_summary.txt"
    ),
    "regression_bilateral_ES_up.txt": (
        "Superseded: old single-stress spec for ES_up; dual-regime version is canonical"
    ),
    "regression_extended_baseline.txt": (
        "Superseded: identical RHS to regression_dual_regime_ES_down.txt"
    ),
    "regression_extended_baseline_params.csv": (
        "Superseded: params from regression_extended_baseline.txt"
    ),
    "regression_params.csv": (
        "Superseded: params from regression_summary.txt (old spec)"
    ),
    "logit_bilateral_depeg_down.txt": (
        "Skipped in paper: replaced by contingency-table evidence in §5.3"
    ),
    "logit_bilateral_depeg_up.txt": (
        "Skipped in paper: replaced by contingency-table evidence in §5.3"
    ),
}


def main() -> None:
    if not TABLES.exists():
        print(f"ERROR: {TABLES} does not exist.")
        return

    ARCHIVE.mkdir(parents=True, exist_ok=True)

    kept = []
    archived = []
    explicitly_archived = []
    missing_keep = []

    for f in sorted(TABLES.iterdir()):
        if f.is_dir():
            continue
        if f.name.startswith("."):
            continue
        if f.name in KEEP_NAMES:
            kept.append(f.name)
            continue
        dest = ARCHIVE / f.name
        if dest.exists():
            dest.unlink()
        shutil.move(str(f), str(dest))
        if f.name in EXPLICIT_ARCHIVE:
            explicitly_archived.append(f.name)
        else:
            archived.append(f.name)

    for name in KEEP_NAMES:
        if not (TABLES / name).exists():
            missing_keep.append(name)

    manifest = ARCHIVE / "README.md"
    with manifest.open("w", encoding="utf-8") as f:
        f.write("# Archive — why files here are not in output/tables/\n\n")
        f.write(f"Last cleanup: {datetime.now().strftime('%Y-%m-%d %H:%M')}\n\n")
        f.write("## Explicitly superseded files\n\n")
        for name, reason in sorted(EXPLICIT_ARCHIVE.items()):
            f.write(f"- `{name}` — {reason}\n")
        f.write("\n## Other files currently in archive\n\n")
        other = [
            p.name
            for p in ARCHIVE.iterdir()
            if p.is_file()
            and p.name not in EXPLICIT_ARCHIVE
            and not p.name.startswith(".")
            and p.name != "README.md"
        ]
        for name in sorted(other):
            f.write(f"- `{name}`\n")
        if not other:
            f.write("(none)\n")

    ts = datetime.now().strftime("%Y-%m-%d %H:%M")
    print(f"Cleanup run at {ts}")
    print(f"Tables dir:  {TABLES}")
    print(f"Archive dir: {ARCHIVE}")
    print()
    print(f"KEPT ({len(kept)} files):")
    for name, section, desc in KEEP_SPEC:
        marker = "✓" if name in kept else "✗ MISSING"
        print(f"  [{section:>8}] {marker:<10} {name}")
        print(f"               → {desc}")
    print()
    if explicitly_archived:
        print(f"EXPLICITLY ARCHIVED ({len(explicitly_archived)} files, superseded & regenerated):")
        for name in sorted(explicitly_archived):
            print(f"  {name}")
            print(f"    └─ {EXPLICIT_ARCHIVE[name]}")
        print()
    if archived:
        print(f"OTHER ARCHIVED ({len(archived)} files):")
        for name in sorted(archived):
            print(f"  {name}")
        print()
    if missing_keep:
        print(f"WARNING: {len(missing_keep)} expected keep-files do not exist:")
        for name in sorted(missing_keep):
            print(f"  {name}")
        print()
    print(f"Archive manifest written to: {manifest}")
    print()
    print("To restore: mv output/tables/_archive/<filename> output/tables/")
    print("To permanently delete archive: rm -rf output/tables/_archive/")


if __name__ == "__main__":
    main()
